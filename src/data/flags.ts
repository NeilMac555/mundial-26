export function flagFor(nation: string): string | null {
  return FLAG_CODES[nation] ?? null;
}

// Unicode regional-indicator flag emoji from a 2-letter ISO code.
// Returns empty string for special codes like gb-eng (no Unicode equivalent).
export function flagEmoji(nation: string): string {
  const code = flagFor(nation);
  if (!code || code.length !== 2) return '';
  const A = 0x1f1e6;
  return String.fromCodePoint(A + code.charCodeAt(0) - 97, A + code.charCodeAt(1) - 97);
}
